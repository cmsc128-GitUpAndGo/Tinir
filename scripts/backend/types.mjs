import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { localStatus } from './local-status.mjs';
localStatus();
const types = execFileSync('node_modules/.bin/supabase', ['gen', 'types', 'typescript', '--local', '--schema', 'public'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
writeFileSync('src/lib/supabase/database.types.ts', '// Generated by npm run backend:types; do not edit by hand.\n'+types.replace(/[ \t]+$/gm, ''));
console.log('Generated public Supabase RPC types.');
